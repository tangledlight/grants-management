/** Opt-in browser smoke test. Resets shared sample data after a successful run. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';
if (process.env.ALLOW_DEMO_RESET !== '1' || !process.env.TEST_BASE_URL) throw new Error('Set TEST_BASE_URL and ALLOW_DEMO_RESET=1 for a disposable demo environment.');
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.setDefaultTimeout(30000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const title = `Browser review ${Date.now()}`;
try {
  await page.goto(process.env.TEST_BASE_URL);
  await page.getByRole('heading', { name: 'Your funding, in focus.' }).waitFor();
  await page.getByRole('button', { name: 'Create grant', exact: true }).click();
  await page.getByLabel('Title *', { exact: true }).fill(title);
  await page.getByLabel('Assigned reviewer', { exact: true }).selectOption('00000000-0000-0000-0000-000000000002');
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await page.getByRole('heading', { name: title, exact: true }).waitFor();
  console.log('Grant created and published through the browser.');
  await page.getByLabel('Mode', { exact: true }).selectOption('applicant');
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
  await card.getByRole('button', { name: 'View grant', exact: true }).click();
  await page.getByRole('button', { name: 'Apply', exact: true }).click();
  await page.getByLabel('Email *', { exact: true }).fill('browser-review@example.org');
  await page.getByLabel('Requested funding (USD) *', { exact: true }).fill('20000.00');
  for (const [index, name] of ['proposal','budget','eligibility'].entries()) await page.locator('input[type=file]').nth(index).setInputFiles(path.resolve(`supabase/fixtures/${name}.pdf`));
  await page.getByRole('button', { name: 'Submit application', exact: true }).waitFor();
  await page.waitForFunction(() => document.body.textContent.split('Uploaded and verified').length - 1 === 3);
  await page.getByRole('button', { name: 'Submit application', exact: true }).click();
  await page.getByRole('heading', { name: 'Submitted information', exact: true }).waitFor();
  console.log('Applicant evidence uploaded, verified and submitted.');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'proposal.pdf', exact: true }).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'proposal.pdf');
  await page.getByLabel('Mode', { exact: true }).selectOption('admin');
  await page.getByLabel('Demo user', { exact: true }).selectOption('00000000-0000-0000-0000-000000000002');
  await page.getByRole('button', { name: 'Review queue', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: title });
  await row.getByRole('button', { name: 'Sam Rivera', exact: true }).click();
  await page.getByRole('heading', { name: 'Review & decision', exact: true }).waitFor();
  await page.getByRole('checkbox').first().check();
  await page.getByLabel('Award amount (USD)', { exact: true }).fill('10000.00');
  await page.getByLabel('Internal note (optional)', { exact: true }).fill('Reviewer-only browser test note');
  await page.getByRole('button', { name: 'Approve application', exact: true }).click();
  const dialog = page.getByRole('dialog');
  assert.ok((await dialog.innerText()).includes('$2,500.00'));
  await dialog.getByRole('button', { name: 'Approve application', exact: true }).click();
  await page.getByText('Decision final:', { exact: false }).waitFor();
  console.log('Assigned reviewer approved a partial award with the correct 25% confirmation.');
  await page.getByLabel('Mode', { exact: true }).selectOption('applicant');
  await page.getByRole('button', { name: 'My Applications', exact: true }).click();
  await page.getByRole('button', { name: title, exact: true }).click();
  await page.getByRole('heading', { name: 'Submitted information', exact: true }).waitFor();
  const text = await page.locator('main').innerText();
  for (const amount of ['$20,000.00','$10,000.00','$2,500.00','$7,500.00']) assert.ok(text.includes(amount), `Missing ${amount}`);
  assert.ok(!text.includes('Reviewer-only browser test note'));
  assert.ok(!text.includes('Total funding budget'));
  await page.reload();
  await page.getByRole('heading', { name: 'Your funding, in focus.' }).waitFor();
  await page.getByLabel('Mode', { exact: true }).selectOption('applicant');
  await page.getByRole('button', { name: 'My Applications', exact: true }).click();
  await page.getByRole('button', { name: title, exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout must fit the viewport');
  console.log('Applicant amounts, note privacy, refresh persistence, document download and mobile layout verified.');
  await page.getByLabel('Mode', { exact: true }).selectOption('admin');
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Reset demo', exact: true }).click();
  await page.getByText('Demo reset. The sample data has been restored for everyone.', { exact: true }).waitFor();
  assert.deepEqual(errors, [], 'Browser JavaScript errors');
  console.log('Browser smoke test passed; shared sample data restored.');
} finally { await browser.close(); }
